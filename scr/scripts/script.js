function handleForm(e) {
  e.preventDefault();
  const btn = document.getElementById("formBtn");
  const orig = btn.textContent;

  btn.textContent = lang === "pt" ? "Enviando..." : "Sending...";

  // Substitua SERVICE_ID e TEMPLATE_ID pelos dados da sua conta
  emailjs.sendForm("SEU_SERVICE_ID", "SEU_TEMPLATE_ID", e.target).then(
    () => {
      btn.textContent = lang === "pt" ? "Enviado! ✓" : "Sent! ✓";
      btn.style.background = "#10B981";
      setTimeout(() => {
        btn.textContent = orig;
        btn.style.background = "";
        e.target.reset();
      }, 3000);
    },
    (error) => {
      console.log("FAILED...", error);
      btn.textContent = lang === "pt" ? "Erro!" : "Error!";
      setTimeout(() => {
        btn.textContent = orig;
      }, 3000);
    },
  );
}

// ─── CHAT ────────────────────────────────────────────────────
let chatOpen = false,
  msgHist = [],
  notifGone = false;

function toggleChat() {
  chatOpen = !chatOpen;
  document.getElementById("chatWin").classList.toggle("open", chatOpen);
  if (chatOpen && !notifGone) {
    const n = document.querySelector(".cnotif");
    if (n) n.remove();
    notifGone = true;
    document.getElementById("cinp").focus();
  }
}

function getT() {
  return new Date().toLocaleTimeString("pt-BR", {
    hour: "2-digit",
    minute: "2-digit",
  });
}

function addMsg(text, type) {
  const c = document.getElementById("cmsgs"),
    t = document.getElementById("typInd");
  const d = document.createElement("div");
  d.className = `msg m${type}`;
  d.innerHTML = text.replace(/\n/g, "<br>") + `<div class="mt">${getT()}</div>`;
  c.insertBefore(d, t);
  c.scrollTop = 99999;
}

function sug(text) {
  document.getElementById("csugs").style.display = "none";
  document.getElementById("cinp").value = text;
  sendMsg();
}

async function sendMsg() {
  const inp = document.getElementById("cinp");
  const text = inp.value.trim();
  if (!text) return;
  inp.value = "";

  addMsg(text, "s");
  msgHist.push({ role: "user", content: text });

  const ty = document.getElementById("typInd");
  ty.classList.add("show");
  document.getElementById("cmsgs").scrollTop = 99999;

  try {
    // Agora o front-end chama SEU próprio back-end, escondendo a chave da IA
    const res = await fetch("http://localhost:3000/api/chat", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ messages: msgHist }),
    });

    if (!res.ok) throw new Error("Falha na comunicação");

    const data = await res.json();
    const reply = data.reply; // O back-end que você escolher deve retornar esse JSON

    ty.classList.remove("show");
    msgHist.push({ role: "assistant", content: reply });
    addMsg(reply, "r");
  } catch (err) {
    ty.classList.remove("show");
    addMsg(
      "Ops, o servidor local parece estar desligado 😅 Tenta de novo depois!",
      "r",
    );
    console.error(err);
  }
}

