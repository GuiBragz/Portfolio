let lang = "pt";
function applyLang() {
  document.querySelectorAll("[data-t]").forEach((el) => {
    const k = el.dataset.t;
    if (T[lang][k] !== undefined) el.innerHTML = T[lang][k];
  });
  document.querySelectorAll("[data-t-ph]").forEach((el) => {
    const k = el.dataset.tPh;
    if (T[lang][k]) el.placeholder = T[lang][k];
  });
  document.documentElement.lang = lang === "pt" ? "pt-BR" : "en";
  document.getElementById("langIco").textContent = lang === "pt" ? "🇧🇷" : "🇺🇸";
  document.getElementById("langLbl").textContent = lang === "pt" ? "PT" : "EN";
}
function toggleLang() {
  lang = lang === "pt" ? "en" : "pt";
  applyLang();
}

